static void send_command(uint8_t cmd) {
    if (I2C_Start(SSD1306_I2C_ADDR, I2C_WRITE)) {
        I2C_Write(SSD1306_CMD_STREAM);
        I2C_Write(cmd);
        I2C_Stop();
    }
}

void SSD1306_Init(void) {
    I2C_Init(400000UL); // 400kHz fast mode

    // Standard SSD1306 Initialization Sequence
    send_command(0xAE); // Display OFF
    send_command(0xD5); // Set Display Clock Divide Ratio
    send_command(0x80);
    send_command(0xA8); // Set Multiplex Ratio
    send_command(0x3F); // 1/64 duty (64 height)
    send_command(0xD3); // Set Display Offset
    send_command(0x00);
    send_command(0x40); // Set Display Start Line = 0
    send_command(0x8D); // Enable Charge Pump
    send_command(0x14);
    send_command(0x20); // Set Memory Addressing Mode (Page Addressing)
    send_command(0x02);
    send_command(0xA1); // Set Segment Re-map (A0/A1)
    send_command(0xC8); // Set COM Output Scan Direction
    send_command(0xDA); // Set COM Pins Hardware Configuration
    send_command(0x12);
    send_command(0x81); // Set Contrast Control
    send_command(0xCF);
    send_command(0xD9); // Set Pre-charge Period
    send_command(0xF1);
    send_command(0xDB); // Set VCOMH Deselect Level
    send_command(0x40);
    send_command(0xA4); // Output Follows RAM Content
    send_command(0xA6); // Set Normal Display
    send_command(0xAF); // Display ON

    SSD1306_Clear();
}

void SSD1306_SetCursor(uint8_t line, uint8_t col) {
    if (line > 7) line = 7;
    if (col > 127) col = 127;

    send_command(0xB0 + line);                  // Set page start address
    send_command(0x00 + (col & 0x0F));          // Set lower column start address
    send_command(0x10 + ((col >> 4) & 0x0F));   // Set higher column start address
}

void SSD1306_Clear(void) {
    for (uint8_t page = 0; page < 8; page++) {
        SSD1306_SetCursor(page, 0);
        if (I2C_Start(SSD1306_I2C_ADDR, I2C_WRITE)) {
            I2C_Write(SSD1306_DATA_STREAM);
            for (uint8_t col = 0; col < SSD1306_WIDTH; col++) {
                I2C_Write(0x00);
            }
            I2C_Stop();
        }
    }
    SSD1306_SetCursor(0, 0);
}

void SSD1306_WriteChar(char c) {
    if (c < 32 || c > 126) c = ' ';
    uint16_t offset = (uint16_t)(c - 32) * 5;

    if (I2C_Start(SSD1306_I2C_ADDR, I2C_WRITE)) {
        I2C_Write(SSD1306_DATA_STREAM);
        for (uint8_t i = 0; i < 5; i++) {
            I2C_Write(pgm_read_byte(&font5x7[offset + i]));
        }
        I2C_Write(0x00); // 1-pixel inter-character spacing
        I2C_Stop();
    }
}

void SSD1306_WriteString(const char* str) {
    if (!str) return;
    while (*str) {
        SSD1306_WriteChar(*str++);
    }
}

void SSD1306_WriteInt(int16_t val) {
    char buf[7];
    int8_t idx = 0;

    if (val < 0) {
        SSD1306_WriteChar('-');
        val = -val;
    }
    if (val == 0) {
        SSD1306_WriteChar('0');
        return;
    }

    while (val > 0) {
        buf[idx++] = (val % 10) + '0';
        val /= 10;
    }
    while (--idx >= 0) {
        SSD1306_WriteChar(buf[idx]);
    }
}

void SSD1306_DrawProgressBar(uint8_t line, uint8_t col, uint8_t width, uint8_t percentage) {
    if (percentage > 100) percentage = 100;
    if (col + width > SSD1306_WIDTH) width = SSD1306_WIDTH - col;

    uint8_t filled_pixels = (uint8_t)(((uint16_t)percentage * (width - 2)) / 100);

    SSD1306_SetCursor(line, col);
    if (I2C_Start(SSD1306_I2C_ADDR, I2C_WRITE)) {
        I2C_Write(SSD1306_DATA_STREAM);

        // Left border
        I2C_Write(0x7E);

        // Body: filled and unfilled
        for (uint8_t i = 0; i < width - 2; i++) {
            if (i < filled_pixels) {
                I2C_Write(0x7E); // Filled solid bar
            } else {
                I2C_Write(0x42); // Outline frame
            }
        }

        // Right border
        I2C_Write(0x7E);
        I2C_Stop();
    }
}
